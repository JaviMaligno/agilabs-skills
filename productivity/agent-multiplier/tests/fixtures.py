"""Synthetic transcripts for the tests. Nothing here comes from a real session."""
import datetime as D
import json
import os
import sys
import time

os.environ["TZ"] = "UTC"
if hasattr(time, "tzset"):
    time.tzset()

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "scripts"))

T0 = D.datetime(2026, 3, 10, 9, 0, 0)


def ts(minutes: float) -> str:
    return (T0 + D.timedelta(minutes=minutes)).strftime("%Y-%m-%dT%H:%M:%S.000Z")


def at(minutes: float) -> D.datetime:
    return T0 + D.timedelta(minutes=minutes)


class Claude:
    """Builds a Claude Code transcript line by line."""

    def __init__(self, cwd="/home/dev/work/client-a-api", entrypoint="cli", sidechain=False):
        self.lines = []
        self.cwd, self.entrypoint, self.sidechain = cwd, entrypoint, sidechain
        self.n = 0

    def _base(self, typ, m):
        self.n += 1
        return {"parentUuid": None, "isSidechain": self.sidechain, "type": typ, "cwd": self.cwd,
                "entrypoint": self.entrypoint, "sessionId": "s1", "uuid": f"u{self.n}", "timestamp": ts(m)}

    def prompt(self, m, text="please do the thing", source="typed"):
        o = self._base("user", m)
        o.update({"promptSource": source, "origin": {"kind": "human"}, "message": {"role": "user", "content": text}})
        if source is None:
            del o["promptSource"], o["origin"]
        self.lines.append(o)
        return self

    def system_prompt(self, m, text, origin_kind="task-notification"):
        o = self._base("user", m)
        o.update({"promptSource": "system", "origin": {"kind": origin_kind}, "message": {"role": "user", "content": text}})
        self.lines.append(o)
        return self

    def meta(self, m, text="<local-command-caveat>Caveat: the messages below were generated by the user while running local commands.</local-command-caveat>"):
        o = self._base("user", m)
        o.update({"isMeta": True, "message": {"role": "user", "content": text}})
        self.lines.append(o)
        return self

    def bare(self, m, text):
        """A user record with no promptSource, origin or isMeta (how some messages from other sessions look)."""
        o = self._base("user", m)
        o["message"] = {"role": "user", "content": text}
        self.lines.append(o)
        return self

    def compaction(self, m):
        o = self._base("user", m)
        o.update({"isCompactSummary": True, "message": {"role": "user", "content": "This session is being continued..."}})
        self.lines.append(o)
        return self

    def text(self, m, text="done"):
        o = self._base("assistant", m)
        o["message"] = {"role": "assistant", "content": [{"type": "text", "text": text}]}
        self.lines.append(o)
        return self

    def tool(self, m, tid, name="Bash", background=False):
        o = self._base("assistant", m)
        inp = {"command": "make test"}
        if background:
            inp["run_in_background"] = True
        o["message"] = {"role": "assistant", "content": [{"type": "tool_use", "id": tid, "name": name, "input": inp}]}
        self.lines.append(o)
        return self

    def result(self, m, tid, source="config", background_id=None, text="ok"):
        o = self._base("user", m)
        o["message"] = {"role": "user", "content": [{"type": "tool_result", "tool_use_id": tid, "content": text}]}
        o["permissionDecision"] = {"decision": "accept", "source": source}
        if background_id:
            o["toolUseResult"] = {"backgroundTaskId": background_id, "stdout": ""}
        self.lines.append(o)
        return self

    def api_error(self, m, text="API Error: Can't reach the API server"):
        o = self._base("assistant", m)
        o.update({"isApiErrorMessage": True, "message": {"role": "assistant", "content": [{"type": "text", "text": text}]}})
        self.lines.append(o)
        return self

    def resume(self, m):
        o = self._base("attachment", m)
        o["attachment"] = {"type": "instructions", "reason": "session_start", "changed": True, "files": []}
        self.lines.append(o)
        return self

    def noise(self, m):
        self.lines.append({"type": "api-request", "sessionId": "s1", "timestamp": ts(m), "params": {}})
        return self

    def write(self, path):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as fh:
            for o in self.lines:
                fh.write(json.dumps(o) + "\n")
        return path


class Codex:
    def __init__(self, cwd="/home/dev/side/tool", originator="codex-tui", source="cli"):
        self.lines = [{"timestamp": ts(0), "type": "session_meta",
                       "payload": {"cwd": cwd, "originator": originator, "source": source, "id": "c1"}}]

    def user(self, m, text="fix the bug"):
        self.lines.append({"timestamp": ts(m), "type": "response_item",
                           "payload": {"type": "message", "role": "user", "content": [{"type": "input_text", "text": text}]}})
        return self

    def agents_md(self, m, folder="/home/dev/side/tool"):
        text = f"# AGENTS.md instructions for {folder}\n\n<INSTRUCTIONS>\n" + "Keep functions small.\n" * 200 + "</INSTRUCTIONS>"
        return self.user(m, text)

    def env(self, m):
        self.lines.append({"timestamp": ts(m), "type": "response_item",
                           "payload": {"type": "message", "role": "user", "content": [{"type": "input_text", "text": "<environment_context>x</environment_context>"}]}})
        return self

    def item(self, m, ptype="function_call"):
        self.lines.append({"timestamp": ts(m), "type": "response_item", "payload": {"type": ptype, "name": "shell"}})
        return self

    def event(self, m, ptype):
        self.lines.append({"timestamp": ts(m), "type": "event_msg", "payload": {"type": ptype}})
        return self

    def write(self, path):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as fh:
            for o in self.lines:
                fh.write(json.dumps(o) + "\n")
        return path
